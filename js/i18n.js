/* ── core helpers ── */
/* Single source of truth for the active language. Everything (t(), the
   buttons, link-stamping) reads this, so the choice can never disagree
   with itself. */
let currentLang = null;

function getLang() {
  if (currentLang === 'sq' || currentLang === 'en') return currentLang;

  /* First call only: seed from URL param (survives navigation) then
     fall back to the saved choice, then the Albanian default. */
  const urlLang = new URLSearchParams(window.location.search).get('lang');
  if (urlLang === 'sq' || urlLang === 'en') {
    currentLang = urlLang;
  } else {
    try { currentLang = localStorage.getItem('sd-lang') || 'sq'; } catch(e) { currentLang = 'sq'; }
  }
  try { localStorage.setItem('sd-lang', currentLang); } catch(e) {}
  return currentLang;
}

function t(key) {
  const parts = key.split('.');
  let val = TRANSLATIONS[getLang()];
  for (const p of parts) val = val?.[p];
  return val ?? key;
}

/* Stamp ?lang=XX onto every internal nav link so clicking carries the choice */
function updateNavLinks(lang) {
  document.querySelectorAll('a[href]').forEach(a => {
    const href = a.getAttribute('href');
    if (!href || href.startsWith('http') || href.startsWith('mailto') || href.startsWith('tel') || href.startsWith('//')) return;
    const [pathPart, anchor] = href.split('#');
    if (!pathPart) return;
    const [path, existingQuery] = pathPart.split('?');
    if (!path) return;
    const params = new URLSearchParams(existingQuery || '');
    params.set('lang', lang);
    a.setAttribute('href', `${path}?${params.toString()}${anchor != null ? '#' + anchor : ''}`);
  });
}

function applyTranslations(forceLang) {
  const lang = forceLang !== undefined ? forceLang : getLang();

  /* plain text nodes */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });

  /* placeholders */
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });

  /* hero headline — last word in gold */
  const heroTitle = document.getElementById('hero-title');
  if (heroTitle) {
    const headline = t('hero.headline');
    const words = headline.trimEnd().split(' ');
    const last = words.pop();
    heroTitle.innerHTML = words.join(' ') + ' <span class="gold">' + last + '</span>';
  }

  /* contact form selects */
  populateSelect('select-project-type', t('contact.projectTypes'), t('contact.selectProject'));
  populateSelect('select-budget', t('contact.budgetRanges'), t('contact.selectBudget'));

  /* page <title> */
  const titleKey = document.body.dataset.pageTitle;
  if (titleKey) document.title = t(titleKey);

  /* lang button active states */
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  /* update all internal links to carry the current language */
  updateNavLinks(lang);
}

function populateSelect(id, options, placeholder) {
  const sel = document.getElementById(id);
  if (!sel || !Array.isArray(options)) return;
  const current = sel.value;
  sel.innerHTML = `<option value="" disabled>${placeholder}</option>`;
  options.forEach(opt => {
    const o = document.createElement('option');
    o.value = opt;
    o.textContent = opt;
    if (opt === current) o.selected = true;
    sel.appendChild(o);
  });
  if (!current) sel.value = '';
}

function setLang(lang) {
  if (lang !== 'sq' && lang !== 'en') return;

  /* Make the new choice authoritative everywhere before re-rendering. */
  currentLang = lang;
  try { localStorage.setItem('sd-lang', lang); } catch(e) {}

  /* Keep the current URL's ?lang in sync so getLang() and a manual
     reload agree with the button. Best-effort: file:// can reject
     replaceState, but the toggle still works because currentLang drives t(). */
  try {
    const url = new URL(window.location.href);
    url.searchParams.set('lang', lang);
    history.replaceState(null, '', url.toString());
  } catch(e) {}

  applyTranslations(lang);
}

